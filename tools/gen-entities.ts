// Generates src/parsing/entities-data.ts from the WHATWG HTML named character references:
//   curl -sSL https://html.spec.whatwg.org/entities.json -o entities.json
//   node tools/gen-entities.ts entities.json
// Only the names ending in `;` are kept: CommonMark recognizes no others.

import { readFileSync, writeFileSync } from 'node:fs';

const source = JSON.parse(readFileSync(process.argv[2]!, 'utf8')) as Record<string, { codepoints: number[] }>;
const entries = Object.entries(source)
  .filter(([name]) => name.endsWith(';'))
  .map(([name, { codepoints }]) => `${name.slice(1, -1)}:${codepoints.map((c) => c.toString(36)).join('.')}`)
  .sort();
const out = `// Generated by tools/gen-entities.ts from https://html.spec.whatwg.org/entities.json; do not edit.
// HTML named character references (those ending in \`;\`): \`name:codepoints\`, code points in base 36
// separated by \`.\`, entries by \`,\`.

export const ENTITY_DATA =
  '${entries.join(',')}';
`;
writeFileSync(new URL('../src/parsing/entities-data.ts', import.meta.url), out);
console.log(`${entries.length} entities`);
